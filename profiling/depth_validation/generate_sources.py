"""The five generated Executor fragments the depth probe is compiled against.

`profiling/native/state_response/generate_probe.py` assembles such a set from the
three pinned executors, but it cannot build *this* instrument. The depth campaign
initialises tensors from a binary asset file, and only the historical
`highlevel_accuracy/highlevel_probe.cpp` blob carries that transport
(`depth_assets::load`); the current probe replaced it with text `initial_values`
and changed which backing tensors get allocated. Regenerating from today's source
would be a different instrument under the same name, and the arithmetic of a
depth campaign is only comparable to the campaign that froze it.

So this script rebuilds the exact five files the published depth campaign ran:

  * `single_layer_generated.inc`, `state_response_generated.inc`,
    `timing_events.inc` and `numeric_helpers.inc` are what the current pinned
    executors produce -- byte-identical to
    `profiling/native/steady_costs/build-release-v2/`;
  * `highlevel_generated.inc` comes from the historical highlevel probe
    (`ceeebc81c00a4fb760923c7b1286a7470558250488f93119c7d628dfed0872eb`,
    commit c3ee2e4) with exactly two additions, both anchored on text that occurs
    once and both required to match:

      1. `#include "initial_assets.hpp"` before `struct Executor {`;
      2. an `initial_assets` branch placed before the `initial_values` branch.

Usage
-----
    python -m profiling.depth_validation.generate_sources --check
    python -m profiling.depth_validation.generate_sources --out <dir>
    python -m profiling.depth_validation.generate_sources --out <dir> \
        --source <historical highlevel_probe.cpp>

`--check` verifies the fragments shipped in `generated/` against their recorded
hashes and needs neither git nor a network. `--out` rewrites them; it reads the
historical blob out of git history unless `--source` names a copy. Whichever way
a fragment is obtained, the written bytes are compared against the recorded
hash: a mismatch is an error, never a newer instrument.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]
GENERATED = Path(__file__).resolve().parent / "generated"
MANIFEST = GENERATED / "source-manifest.json"

# The four executor sources the fragments are cut from. The highlevel entry is
# the historical blob; the other three are the current pins, which are also what
# `profiling/native/state_response/generate_probe.py` publishes.
HISTORICAL_HIGHLEVEL = "profiling/native/highlevel_accuracy/highlevel_probe.cpp"
EXECUTORS = {
    HISTORICAL_HIGHLEVEL:
        "ceeebc81c00a4fb760923c7b1286a7470558250488f93119c7d628dfed0872eb",
    "profiling/native/single_layer_calibration/probe.cpp":
        "27f8360fc6e54a090dec777c21a835d1ec29db2810aa4e453e6fb020401cb9a6",
    "profiling/native/state_calibration/compute.cpp":
        "bb2ace018e543c706d72563f7c61ccd260a58a4cde79354b76d5dd950959fc78",
    "profiling/native/state_response/probe.cpp":
        "97fefd7c21e6b711ab354083bb23098ea06d4e3c72b09f19fa85d69b092a3a7b",
}
CURRENT = ("profiling/native/single_layer_calibration/probe.cpp",
           "profiling/native/state_calibration/compute.cpp",
           "profiling/native/state_response/probe.cpp")
HISTORICAL_COMMIT = "c3ee2e4"
HISTORICAL_RELATIVE = "profiling/native/highlevel_accuracy/highlevel_probe.cpp"

# The recorded hashes of the published set. A regenerated byte string is
# accepted only when it is one of these.
RECORDED = {
    "highlevel_generated.inc":
        "fc03bc44ee159bfe343c0c5d1a8ef00cd24fdc4ed4572f91e9e8a1403415b786",
    "single_layer_generated.inc":
        "ea17360bd3cb04b7ebf147ee762724a041c27256c2dfdc510c0e2b06772e54f0",
    "state_response_generated.inc":
        "296647e95a7b25ea04d266172562c4b9256fbf65c0b934516281235c5af5450b",
    "timing_events.inc":
        "04a87f7214fdd20bae1dcda70c6004850bdaaaf3410c4b305419a0fc35f739e2",
    "numeric_helpers.inc":
        "775c3c0df93606d058bf4299edb42770e3fbbc74d88ff9b9668d041c251a761e",
}

MAIN = b"int main(int argc,char **argv)"
# Each fragment renames the entry point of the one it wraps; the names are the
# ones `profiling/native/state_response/generate_probe.py` uses.
RENAMED = {
    "highlevel_generated.inc": b"static int single_layer_historical_main(int argc,char **argv)",
    "single_layer_generated.inc": b"static int state_response_historical_main(int argc,char **argv)",
    "state_response_generated.inc": b"static int steady_costs_unused_state_main(int argc,char **argv)",
}
GRAPH_ANCHOR = b"struct Executor {"
ASSET_INCLUDE = b"#include \"initial_assets.hpp\"\n"
VALUES_ANCHOR = b"            if(program.at(\"initial_values\").contains(id)){"
VALUES_BRANCH = (b"            if(program.contains(\"initial_assets\")"
                 b" && program.at(\"initial_assets\").at(\"tensors\").contains(id)){\n"
                 b"                t.initial=depth_assets::load(program,id,bytes,dtype);\n"
                 b"            }else if(program.at(\"initial_values\").contains(id)){")


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def extract(state: bytes, first: bytes, last: bytes) -> bytes:
    if state.count(first) != 1 or state.count(last) != 1:
        raise ValueError("ambiguous pinned helper boundary")
    return state[state.index(first):state.index(last)]


def once(text: bytes, anchor: bytes, replacement: bytes, what: str) -> bytes:
    if text.count(anchor) != 1:
        raise ValueError(f"{what}: anchor occurs {text.count(anchor)} times")
    return text.replace(anchor, replacement, 1)


def historical_source(explicit: Path | None) -> bytes:
    """The highlevel probe blob the depth instrument was built from."""
    relative = HISTORICAL_RELATIVE
    if explicit is not None:
        data = Path(explicit).read_bytes()
        origin = str(explicit)
    else:
        done = subprocess.run(["git", "-C", str(ROOT), "show",
                               f"{HISTORICAL_COMMIT}:{relative}"],
                              capture_output=True)
        if done.returncode != 0:
            raise SystemExit(
                "the historical highlevel probe is not available in this checkout "
                f"({done.stderr.decode('utf-8', 'replace').strip()}).\n"
                "A full clone has it: `git show "
                f"{HISTORICAL_COMMIT}:{relative}`. Otherwise pass "
                "--source with a byte-identical copy; the file must hash to "
                f"{EXECUTORS[relative]}.")
        data = done.stdout
        origin = f"git {HISTORICAL_COMMIT}"
    if sha(data) != EXECUTORS[relative]:
        raise SystemExit(f"{origin}: highlevel probe hashes to {sha(data)}, "
                         f"expected {EXECUTORS[relative]}")
    return data


def fragments(highlevel: bytes, single: bytes, state: bytes, response: bytes) -> dict[str, bytes]:
    if highlevel.count(MAIN) != 1 or single.count(MAIN) != 1 or response.count(MAIN) != 1:
        raise ValueError("ambiguous main symbol")
    high = highlevel.replace(MAIN, RENAMED["highlevel_generated.inc"])
    high = once(high, GRAPH_ANCHOR, ASSET_INCLUDE + GRAPH_ANCHOR,
                "initial-assets include")
    high = once(high, VALUES_ANCHOR, VALUES_BRANCH, "initial-assets branch")
    return {
        "highlevel_generated.inc": high,
        "single_layer_generated.inc": single.replace(MAIN, RENAMED["single_layer_generated.inc"]),
        "state_response_generated.inc":
            response.replace(MAIN, RENAMED["state_response_generated.inc"]),
        "timing_events.inc": extract(state, b"static void cuda_ok(", b"struct TargetTiming {"),
        "numeric_helpers.inc": extract(state, b"static json compare_ports(", b"static json graph_description("),
    }


def build(explicit: Path | None = None) -> dict[str, bytes]:
    originals = {name: (ROOT / name).read_bytes() for name in CURRENT}
    for name, data in originals.items():
        if sha(data) != EXECUTORS[name]:
            raise SystemExit(f"{name}: pinned executor changed ({sha(data)})")
    produced = fragments(historical_source(explicit),
                         originals["profiling/native/single_layer_calibration/probe.cpp"],
                         originals["profiling/native/state_calibration/compute.cpp"],
                         originals["profiling/native/state_response/probe.cpp"])
    for name, data in produced.items():
        if sha(data) != RECORDED[name]:
            raise SystemExit(f"{name}: regenerated bytes hash to {sha(data)}, "
                             f"recorded {RECORDED[name]}; this is a different instrument")
    return produced


def manifest(produced: dict[str, bytes]) -> dict:
    return {
        "format_version": "depth-executor-fragments-1",
        "generated_files": {name: sha(data) for name, data in sorted(produced.items())},
        "executors": EXECUTORS,
        "historical_highlevel_commit": HISTORICAL_COMMIT,
        "historical_highlevel_why":
            "the depth campaigns initialise tensors from a binary asset file; only this "
            "blob carries depth_assets::load. The current probe dropped that transport "
            "and changed which backing tensors are allocated, so it is a different "
            "instrument, not a newer one.",
        "injections": [
            {"anchor": GRAPH_ANCHOR.decode(), "inserted": ASSET_INCLUDE.decode().strip()},
            {"anchor": VALUES_ANCHOR.decode(), "inserted": VALUES_BRANCH.decode().split("\n")[0].strip()},
        ],
        "unchanged_fragments":
            "single_layer, state_response, timing_events and numeric_helpers are what the "
            "current pinned executors produce; they match "
            "profiling/native/steady_costs/build-release-v2 byte for byte.",
        "regenerate": "python -m profiling.depth_validation.generate_sources --out "
                      "profiling/depth_validation/generated",
        "verify": "python -m profiling.depth_validation.generate_sources --check",
    }


def check() -> int:
    recorded = json.loads(MANIFEST.read_text(encoding="utf-8"))["generated_files"]
    problems = []
    for name, expected in sorted(recorded.items()):
        path = GENERATED / name
        if not path.is_file():
            problems.append(f"{name}: missing")
        elif sha(path.read_bytes()) != expected:
            problems.append(f"{name}: {sha(path.read_bytes())} != {expected}")
        elif expected != RECORDED[name]:
            problems.append(f"{name}: manifest records {expected}, this script pins {RECORDED[name]}")
    for name in sorted(set(RECORDED) - set(recorded)):
        problems.append(f"{name}: not recorded in the manifest")
    for problem in problems:
        print(problem)
    return 1 if problems else 0


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", type=Path, help="directory to write the five fragments into")
    parser.add_argument("--source", type=Path,
                        help="byte-identical copy of the historical highlevel probe")
    parser.add_argument("--check", action="store_true",
                        help="verify the shipped fragments against their recorded hashes")
    args = parser.parse_args(argv)
    if args.check:
        return check()
    if args.out is None:
        parser.error("one of --out or --check is required")
    produced = build(args.source)
    args.out.mkdir(parents=True, exist_ok=True)
    for name, data in sorted(produced.items()):
        (args.out / name).write_bytes(data)
    if args.out.resolve() == GENERATED.resolve():
        (GENERATED / "source-manifest.json").write_text(
            json.dumps(manifest(produced), indent=2) + "\n", encoding="utf-8", newline="\n")
    print(json.dumps({name: sha(data) for name, data in sorted(produced.items())}, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
