"""Extract the frozen v6 owned-actor mechanism without editing its source."""
from pathlib import Path
import argparse
import hashlib

HERE=Path(__file__).resolve().parent
ORIGINAL=HERE/'native/v6/external_probe.cpp'
DESTINATION=HERE/'native/v8/actors.inc'


def render(text):
    begin='namespace dynamic_external_v6 {'
    end='struct Stamp {int64_t begin=0,end=0;};'
    if text.count(begin)!=1 or text.count(end)!=1:
        raise ValueError('frozen v6 actor source anchors differ')
    a,b=text.index(begin),text.index(end)
    if a>=b:raise ValueError('actor source anchor order differs')
    body=text[a:b].replace(begin,'namespace external_stage_v8 {',1)
    return '// Generated by actor_source_v8.py from the unchanged v6 actor prefix.\n'+body+'}\n'


def check():
    expected=render(ORIGINAL.read_text(encoding='utf-8'))
    if not DESTINATION.is_file() or DESTINATION.read_text(encoding='utf-8')!=expected:
        raise ValueError('v8 actor include no longer exactly derives from the bound v6 source')
    return dict(original=str(ORIGINAL),original_sha256=hashlib.sha256(ORIGINAL.read_bytes()).hexdigest(),
                derived=str(DESTINATION),derived_sha256=hashlib.sha256(DESTINATION.read_bytes()).hexdigest())


if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('command',choices=('write','check'));a=p.parse_args()
    if a.command=='write':
        if DESTINATION.exists():raise FileExistsError('new actor include only; no overwrite')
        DESTINATION.parent.mkdir(parents=True,exist_ok=True)
        DESTINATION.write_text(render(ORIGINAL.read_text(encoding='utf-8')),encoding='utf-8',newline='\n')
    print(check())
