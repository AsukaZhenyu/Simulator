"""The depth instrument's inputs: fixed fragments, one deviating source, one adapter.

A depth campaign prices the *same* executor that produced the published table, so
the thing to test is not the campaign arithmetic -- it runs elsewhere, on a
machine with a GPU -- but that a clone can rebuild the identical probe:

  * the five generated fragments shipped in `generated/` hash to what the
    published campaign compiled, and can be regenerated byte for byte from the
    pinned executors;
  * the highlevel fragment carries the binary initial-asset transport, because
    the current highlevel probe does not;
  * `campaign.executor_fragments` refuses a directory of *different* fragments
    instead of measuring a newer instrument under an old name;
  * `prepare_portable` replaces exactly the machine-specific fields of the
    context and keeps the protocol constants verbatim.

Nothing here needs a GPU, a compiler or a previous campaign.
"""
from __future__ import annotations

import json
import shutil
import sys
import tempfile
import unittest
from pathlib import Path

from profiling import host
from profiling.depth_validation import campaign
from profiling.depth_validation import generate_sources as gen
from profiling.depth_validation import prepare_portable


def library(stem: str) -> str:
    """A file name this host's loader would find for a library named `stem`."""
    pattern = host.shared_library_pattern()
    return stem + {"*.dll": ".dll", "*.dylib": ".dylib", "*.so*": ".so"}[pattern]


class ShippedFragmentTests(unittest.TestCase):
    def test_the_shipped_fragments_match_their_recorded_hashes(self):
        self.assertEqual(gen.check(), 0)

    def test_the_manifest_names_every_fragment_the_campaign_compiles(self):
        recorded = json.loads(gen.MANIFEST.read_text(encoding="utf-8"))["generated_files"]
        self.assertEqual(recorded, gen.RECORDED)
        self.assertEqual({p.name for p in gen.GENERATED.glob("*.inc")}, set(recorded))

    def test_the_fragments_regenerate_byte_for_byte_from_the_pinned_executors(self):
        try:
            produced = gen.build()
        except SystemExit as error:
            # A shallow clone does not carry the historical blob; the shipped
            # bytes still hash-check above, so this is a missing prerequisite,
            # not a difference in the instrument.
            if "historical highlevel probe is not available" in str(error):
                self.skipTest("this checkout does not carry commit " + gen.HISTORICAL_COMMIT)
            raise
        self.assertEqual({name: gen.sha(data) for name, data in produced.items()}, gen.RECORDED)

    def test_the_depth_variant_carries_the_binary_asset_transport(self):
        current = (gen.ROOT / gen.HISTORICAL_RELATIVE).read_bytes()
        shipped = (gen.GENERATED / "highlevel_generated.inc").read_bytes()
        # The reason this file deviates at all: the transport is gone upstream.
        self.assertNotIn(b"depth_assets", current)
        self.assertIn(b'#include "initial_assets.hpp"', shipped)
        self.assertIn(b"depth_assets::load(program,id,bytes,dtype)", shipped)
        self.assertIn(b'if(program.contains("initial_assets")', shipped)

    def test_every_fragment_renames_its_entry_point_exactly_once(self):
        for name in gen.RECORDED:
            data = (gen.GENERATED / name).read_bytes()
            self.assertEqual(data.count(b"int main(int argc,char **argv)"), 0, name)
            if name in gen.RENAMED:
                self.assertEqual(data.count(gen.RENAMED[name]), 1, name)


class FragmentSelectionTests(unittest.TestCase):
    def test_the_repository_copy_is_accepted_and_labelled(self):
        directory, label, recorded = campaign.executor_fragments([(gen.GENERATED, "repository")])
        self.assertEqual(directory, gen.GENERATED)
        self.assertEqual(label, "repository")
        self.assertEqual(recorded, gen.RECORDED)

    def test_a_directory_of_other_fragments_is_refused(self):
        with tempfile.TemporaryDirectory(prefix="depth-fragments-") as folder:
            altered = Path(folder)
            for name in gen.RECORDED:
                shutil.copy2(gen.GENERATED / name, altered / name)
            (altered / "highlevel_generated.inc").write_bytes(
                (altered / "highlevel_generated.inc").read_bytes() + b"// a newer instrument\n")
            with self.assertRaises(ValueError):
                campaign.executor_fragments([(altered, "altered")])

    def test_a_missing_directory_is_skipped_rather_than_used(self):
        with tempfile.TemporaryDirectory(prefix="depth-empty-") as folder:
            directory, label, _ = campaign.executor_fragments(
                [(Path(folder) / "absent", "absent"), (gen.GENERATED, "repository")])
        self.assertEqual(label, "repository")


class PortableDescriptorTests(unittest.TestCase):
    def setUp(self):
        self.folder = tempfile.TemporaryDirectory(prefix="depth-portable-")
        self.addCleanup(self.folder.cleanup)
        root = Path(self.folder.name)
        self.runtime = root / "runtime"
        self.runtime.mkdir()
        self.base = library("ggml-base")
        self.cpu = library("ggml-cpu")
        # All three: the probe loads ggml-cuda as well, and a runtime holding the
        # first two is exactly the half-built case the adapter now refuses.
        self.cuda = library("ggml-cuda")
        (self.runtime / self.base).write_bytes(b"not a real library")
        (self.runtime / self.cpu).write_bytes(b"also not real")
        (self.runtime / self.cuda).write_bytes(b"nor is this")
        self.binary = root / host.executable_name("depth-probe")
        self.binary.write_bytes(b"neither is this")

    def test_the_context_keeps_the_protocol_and_replaces_the_machine(self):
        try:
            expected_mask, expected_thread, expected_cpus = (
                host.process_affinity_mask(), host.main_thread_mask(), host.online_cpus())
        except host.UnsupportedHost as error:
            self.skipTest("this host cannot honour the protocol: " + str(error))
        supplied = prepare_portable.descriptor(self.binary, [self.runtime])
        context = supplied["baseline_context"]
        for key, value in prepare_portable.PROTOCOL.items():
            self.assertEqual(context[key], value, key)
        self.assertEqual(context["hardware"]["unknown_identity_fields_are_not_inferred"], True)
        self.assertEqual(set(context["runtime_dlls"]), {str(self.runtime / self.base),
                                                        str(self.runtime / self.cpu),
                                                        str(self.runtime / self.cuda)})
        # The affinity mask and the main-thread mask are properties of this
        # machine, so they are asked of it rather than carried in the protocol.
        self.assertNotIn("process_affinity_mask", prepare_portable.PROTOCOL)
        self.assertNotIn("main_thread_mask", prepare_portable.PROTOCOL)
        self.assertEqual(context["process_affinity_mask"], expected_mask)
        self.assertEqual(context["main_thread_mask"], expected_thread)
        self.assertEqual(context["online_cpus"], expected_cpus)

    def test_the_runtime_receipts_cover_every_library_and_keep_the_directory_order(self):
        supplied = prepare_portable.descriptor(self.binary, [self.runtime])
        self.assertEqual([row["path"] for row in supplied["runtime"]],
                         [str(self.runtime / self.base), str(self.runtime / self.cpu),
                          str(self.runtime / self.cuda)])
        self.assertEqual(supplied["runtime_dirs"], [str(self.runtime.resolve())])

    def test_a_runtime_directory_without_libraries_is_refused(self):
        empty = Path(self.folder.name) / "empty"
        empty.mkdir()
        with self.assertRaises(ValueError):
            prepare_portable.descriptor(self.binary, [empty])

    def test_the_replaced_descriptor_is_the_archived_h2d_manifest(self):
        self.assertEqual(prepare_portable.LEGACY,
                         campaign.ROOT / "build/h2d-history-20261026/campaign-v1/manifest.json")


class PreparationReadsNothingMeasured(unittest.TestCase):
    # This one test is the exception to the module's "no previous campaign"
    # rule: it checks the adapter against the archived H2D manifest, which lives
    # in `build/` and is not in the repository. On a checkout without the
    # archive the adapter's only path cannot be exercised, and a skip says so
    # instead of a green run that never reached the code.
    @unittest.skipUnless(prepare_portable.LEGACY.is_file(),
                         "the archived H2D campaign is not in this checkout")
    def test_the_adapter_answers_the_legacy_descriptor_and_nothing_else(self):
        # The one archived path the adapter replaces is the H2D descriptor; every
        # other read must still reach the disk, so a missing frozen profile or
        # prediction cannot be papered over by the adapter.
        asked = []
        original = campaign.read
        campaign.read = lambda path: asked.append(str(path)) or original(path)
        try:
            campaign.read(prepare_portable.LEGACY)
        finally:
            campaign.read = original
        self.assertEqual(asked, [str(prepare_portable.LEGACY)])

        supplied = dict(baseline_context={}, runtime=[], runtime_dirs=[])
        campaign.read = lambda path: supplied if Path(path) == prepare_portable.LEGACY else original(path)
        try:
            self.assertEqual(campaign.read(prepare_portable.LEGACY)["runtime_dirs"], [])
            with self.assertRaises(FileNotFoundError):
                campaign.read(Path(tempfile.gettempdir()) / "no-such-campaign-manifest.json")
        finally:
            campaign.read = original


if __name__ == "__main__":
    unittest.main()
